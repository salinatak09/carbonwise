import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import Navbar from "@/components/ui/Navbar";
import { auth } from "@/lib/auth";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "CarbonWise - Personal Carbon Footprint Tracker",
  description: "Track your transportation, food meals, and power usage. Get customized reduction strategies powered by Google Gemini AI.",
  keywords: ["carbon footprint", "sustainability", "emissions calculator", "eco tracker", "green habits", "India carbon levels"],
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const session = await auth();

  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col bg-slate-50 text-slate-900 dark:bg-slate-950 dark:text-slate-100">
        <Navbar session={session} />
        <main className="flex-1 w-full pt-6">
          {children}
        </main>
      </body>
    </html>
  );
}
